BEGIN;
CREATE TABLE curso (
    id_curso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(180) NOT NULL CHECK (btrim(nombre)<>''),
    descripcion TEXT NOT NULL CHECK (btrim(descripcion)<>''),
    cupo_maximo INTEGER NOT NULL CHECK (cupo_maximo > 0),
    estado VARCHAR(10) NOT NULL DEFAULT 'ABIERTO'
        CHECK (estado IN ('ABIERTO','CERRADO')),
    id_profesor BIGINT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
    imagen_url VARCHAR(500) NULL CHECK (imagen_url IS NULL OR btrim(imagen_url)<>'')
);
CREATE INDEX idx_curso_estado ON curso(estado);
CREATE INDEX idx_curso_profesor ON curso(id_profesor);

CREATE TABLE horario (
    id_horario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_curso BIGINT NOT NULL REFERENCES curso(id_curso) ON DELETE RESTRICT,
    dia_semana SMALLINT NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    CONSTRAINT ck_horario_orden CHECK (hora_inicio < hora_fin),
    CONSTRAINT uq_horario_exacto UNIQUE (id_curso, dia_semana, hora_inicio, hora_fin)
);
CREATE INDEX idx_horario_curso_dia ON horario(id_curso, dia_semana);

CREATE TABLE inscripcion (
    id_inscripcion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
    id_curso BIGINT NOT NULL REFERENCES curso(id_curso) ON DELETE RESTRICT,
    fecha_inscripcion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    estado VARCHAR(12) NOT NULL DEFAULT 'CONFIRMADA'
        CHECK (estado IN ('CONFIRMADA','FINALIZADA')),
    CONSTRAINT uq_inscripcion_usuario_curso UNIQUE (id_usuario, id_curso)
);
CREATE INDEX idx_inscripcion_curso_estado ON inscripcion(id_curso, estado);
CREATE INDEX idx_inscripcion_usuario ON inscripcion(id_usuario);

CREATE TABLE asistencia (
    id_asistencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_inscripcion BIGINT NOT NULL REFERENCES inscripcion(id_inscripcion) ON DELETE RESTRICT,
    fecha DATE NOT NULL,
    estado_asistencia VARCHAR(8) NOT NULL
        CHECK (estado_asistencia IN ('PRESENTE','AUSENTE')),
    CONSTRAINT uq_asistencia_inscripcion_fecha UNIQUE (id_inscripcion, fecha)
);
CREATE INDEX idx_asistencia_fecha ON asistencia(fecha);

CREATE FUNCTION validar_profesor_curso() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.id_profesor IS NOT NULL AND NOT EXISTS (
       SELECT 1 FROM usuario u
       JOIN usuario_rol ur ON ur.id_usuario=u.id_usuario
       JOIN rol r ON r.id_rol=ur.id_rol
       WHERE u.id_usuario=NEW.id_profesor AND u.activo
         AND lower(r.nombre)=lower('Profesor')
    ) THEN
       RAISE EXCEPTION 'El usuario % no es un Profesor activo', NEW.id_profesor;
    END IF;
    RETURN NEW;
END; $$ LANGUAGE plpgsql;
CREATE TRIGGER trg_validar_profesor_curso
BEFORE INSERT OR UPDATE OF id_profesor ON curso
FOR EACH ROW EXECUTE FUNCTION validar_profesor_curso();

CREATE FUNCTION validar_solapamiento_horario() RETURNS TRIGGER AS $$
DECLARE v_profesor BIGINT;
BEGIN
    SELECT id_profesor INTO v_profesor FROM curso
    WHERE id_curso=NEW.id_curso FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Curso inexistente'; END IF;
    IF v_profesor IS NOT NULL THEN
       PERFORM 1 FROM usuario WHERE id_usuario=v_profesor FOR UPDATE;
    END IF;
    IF EXISTS (
       SELECT 1 FROM horario h JOIN curso c ON c.id_curso=h.id_curso
       WHERE h.dia_semana=NEW.dia_semana
         AND h.hora_inicio<NEW.hora_fin AND NEW.hora_inicio<h.hora_fin
         AND (h.id_curso=NEW.id_curso OR
              (v_profesor IS NOT NULL AND c.id_profesor=v_profesor))
         AND (TG_OP='INSERT' OR h.id_horario<>NEW.id_horario)
    ) THEN
       RAISE EXCEPTION 'Conflicto de horario en el curso o profesor asignado';
    END IF;
    RETURN NEW;
END; $$ LANGUAGE plpgsql;
CREATE TRIGGER trg_validar_solapamiento_horario
BEFORE INSERT OR UPDATE OF id_curso, dia_semana, hora_inicio, hora_fin ON horario
FOR EACH ROW EXECUTE FUNCTION validar_solapamiento_horario();

CREATE FUNCTION validar_horarios_al_asignar_profesor() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.id_profesor IS NULL THEN RETURN NEW; END IF;
    PERFORM 1 FROM usuario WHERE id_usuario=NEW.id_profesor FOR UPDATE;
    IF EXISTS (
       SELECT 1 FROM horario nuevo
       JOIN horario otro ON otro.dia_semana=nuevo.dia_semana
         AND otro.hora_inicio<nuevo.hora_fin
         AND nuevo.hora_inicio<otro.hora_fin
       JOIN curso c ON c.id_curso=otro.id_curso
       WHERE nuevo.id_curso=NEW.id_curso
         AND otro.id_curso<>NEW.id_curso
         AND c.id_profesor=NEW.id_profesor
    ) THEN
       RAISE EXCEPTION 'Profesor asignado presenta conflicto de horarios';
    END IF;
    RETURN NEW;
END; $$ LANGUAGE plpgsql;
CREATE TRIGGER trg_validar_horario_profesor_asignacion
BEFORE INSERT OR UPDATE OF id_profesor ON curso
FOR EACH ROW EXECUTE FUNCTION validar_horarios_al_asignar_profesor();

CREATE FUNCTION validar_cupo_inscripcion() RETURNS TRIGGER AS $$
DECLARE v_cupo INT; v_estado VARCHAR(10); v_ocupados INT; v_incremento INT;
BEGIN
    IF TG_OP='UPDATE' THEN
        IF NEW.id_usuario<>OLD.id_usuario THEN
            RAISE EXCEPTION 'No se permite cambiar el titular de una inscripcion';
        END IF;
    END IF;
    SELECT cupo_maximo,estado INTO v_cupo,v_estado
    FROM curso WHERE id_curso=NEW.id_curso FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Curso no encontrado'; END IF;
    IF NEW.estado='CONFIRMADA' THEN
        IF v_estado<>'ABIERTO' THEN
            IF TG_OP='INSERT' THEN
                RAISE EXCEPTION 'El curso esta cerrado';
            ELSIF OLD.estado<>'CONFIRMADA' OR OLD.id_curso<>NEW.id_curso THEN
                RAISE EXCEPTION 'El curso esta cerrado';
            END IF;
        END IF;
        IF TG_OP='INSERT' AND NOT EXISTS (
            SELECT 1 FROM usuario u JOIN usuario_rol ur ON ur.id_usuario=u.id_usuario
            JOIN rol r ON r.id_rol=ur.id_rol
            WHERE u.id_usuario=NEW.id_usuario AND u.activo
              AND r.nombre IN ('Cliente','Estudiante')
        ) THEN RAISE EXCEPTION 'Se requiere cuenta activa con rol Cliente o Estudiante'; END IF;
        SELECT count(*) INTO v_ocupados FROM inscripcion i
        WHERE i.id_curso=NEW.id_curso AND i.estado='CONFIRMADA';
        v_incremento := 1;
        IF TG_OP='UPDATE' THEN
            IF OLD.estado='CONFIRMADA' AND OLD.id_curso=NEW.id_curso THEN
                v_incremento := 0;
            END IF;
        END IF;
        IF v_ocupados + v_incremento > v_cupo THEN
            RAISE EXCEPTION 'No hay cupos disponibles en el curso %', NEW.id_curso;
        END IF;
    END IF;
    RETURN NEW;
END; $$ LANGUAGE plpgsql;
CREATE TRIGGER trg_validar_cupo_inscripcion
BEFORE INSERT OR UPDATE OF id_curso,estado ON inscripcion
FOR EACH ROW EXECUTE FUNCTION validar_cupo_inscripcion();

CREATE FUNCTION validar_reduccion_cupo() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.cupo_maximo < (
       SELECT count(*) FROM inscripcion WHERE id_curso=NEW.id_curso AND estado='CONFIRMADA'
    ) THEN
       RAISE EXCEPTION 'Cupo maximo inferior a las inscripciones confirmadas';
    END IF;
    RETURN NEW;
END; $$ LANGUAGE plpgsql;
CREATE TRIGGER trg_validar_reduccion_cupo
BEFORE UPDATE OF cupo_maximo ON curso
FOR EACH ROW EXECUTE FUNCTION validar_reduccion_cupo();

CREATE FUNCTION asignar_rol_estudiante() RETURNS TRIGGER AS $$
DECLARE v_id_rol BIGINT;
BEGIN
    IF NEW.estado='CONFIRMADA' THEN
        SELECT id_rol INTO v_id_rol FROM rol WHERE nombre='Estudiante';
        IF v_id_rol IS NULL THEN RAISE EXCEPTION 'No existe el rol Estudiante'; END IF;
        INSERT INTO usuario_rol(id_usuario,id_rol)
        VALUES (NEW.id_usuario,v_id_rol)
        ON CONFLICT DO NOTHING;
    END IF;
    RETURN NULL;
END; $$ LANGUAGE plpgsql;
CREATE TRIGGER trg_asignar_rol_estudiante
AFTER INSERT OR UPDATE OF estado ON inscripcion
FOR EACH ROW EXECUTE FUNCTION asignar_rol_estudiante();

CREATE FUNCTION validar_asistencia_inscripcion() RETURNS TRIGGER AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM inscripcion
                   WHERE id_inscripcion=NEW.id_inscripcion AND estado='CONFIRMADA') THEN
       RAISE EXCEPTION 'La asistencia requiere una inscripcion confirmada';
    END IF;
    RETURN NEW;
END; $$ LANGUAGE plpgsql;
CREATE TRIGGER trg_validar_asistencia_inscripcion
BEFORE INSERT OR UPDATE OF id_inscripcion ON asistencia
FOR EACH ROW EXECUTE FUNCTION validar_asistencia_inscripcion();
COMMIT;
