BEGIN;
CREATE TABLE carrito (
    id_carrito BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL UNIQUE REFERENCES usuario(id_usuario) ON DELETE RESTRICT
);

CREATE TABLE linea_carrito (
    id_carrito BIGINT NOT NULL REFERENCES carrito(id_carrito) ON DELETE CASCADE,
    id_producto BIGINT NOT NULL REFERENCES producto(id_producto) ON DELETE RESTRICT,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    PRIMARY KEY (id_carrito, id_producto)
);
CREATE INDEX idx_linea_carrito_producto ON linea_carrito(id_producto);

CREATE TABLE pedido (
    id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    total NUMERIC(14,2) NOT NULL CHECK (total > 0),
    modalidad_entrega VARCHAR(12) NOT NULL CHECK (modalidad_entrega IN ('ENVIO','RETIRO')),
    direccion_entrega TEXT,
    estado_pago VARCHAR(12) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado_pago IN ('PENDIENTE','CONFIRMADO')),
    estado_operativo VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado_operativo IN (
            'PENDIENTE','EN_PREPARACION','EMPACADO','ENVIADO','LISTO_RETIRO','RETIRADO')),
    fecha_confirmacion TIMESTAMPTZ,
    CONSTRAINT ck_pedido_direccion CHECK (
       (modalidad_entrega='ENVIO' AND direccion_entrega IS NOT NULL
         AND btrim(direccion_entrega)<>'')
       OR (modalidad_entrega='RETIRO' AND direccion_entrega IS NULL)
    ),
    CONSTRAINT ck_pedido_confirmacion CHECK (
       (estado_pago='PENDIENTE' AND fecha_confirmacion IS NULL)
       OR (estado_pago='CONFIRMADO' AND fecha_confirmacion IS NOT NULL)
    ),
    CONSTRAINT ck_pedido_estado_operativo CHECK (
       estado_pago='CONFIRMADO' OR estado_operativo='PENDIENTE'
    ),
    CONSTRAINT ck_pedido_modalidad_estado CHECK (
       (modalidad_entrega='ENVIO' AND estado_operativo NOT IN ('LISTO_RETIRO','RETIRADO'))
       OR (modalidad_entrega='RETIRO' AND estado_operativo NOT IN ('EMPACADO','ENVIADO'))
    )
);
CREATE INDEX idx_pedido_usuario_fecha ON pedido(id_usuario, fecha_creacion DESC);
CREATE INDEX idx_pedido_estado_pago ON pedido(estado_pago);

CREATE TABLE detalle_pedido (
    id_pedido BIGINT NOT NULL REFERENCES pedido(id_pedido) ON DELETE RESTRICT,
    id_producto BIGINT NOT NULL REFERENCES producto(id_producto) ON DELETE RESTRICT,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(12,2) NOT NULL CHECK (precio_unitario > 0),
    PRIMARY KEY (id_pedido, id_producto)
);
CREATE INDEX idx_detalle_producto ON detalle_pedido(id_producto);

CREATE TABLE intento_pago_simulado (
    id_intento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL REFERENCES pedido(id_pedido) ON DELETE RESTRICT,
    codigo_escenario VARCHAR(40) NOT NULL CHECK (btrim(codigo_escenario) <> ''),
    resultado_simulacion VARCHAR(12) NOT NULL
        CHECK (resultado_simulacion IN ('APROBADO','RECHAZADO')),
    resultado_confirmacion VARCHAR(22) NOT NULL CHECK (resultado_confirmacion IN (
        'CONFIRMADO','RECHAZADO_PAGO','RECHAZADO_STOCK')),
    fecha_intento TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_intento_coherente CHECK (
      (resultado_simulacion='RECHAZADO' AND resultado_confirmacion='RECHAZADO_PAGO')
      OR (resultado_simulacion='APROBADO'
             AND resultado_confirmacion IN ('CONFIRMADO','RECHAZADO_STOCK'))
    )
);
CREATE INDEX idx_intento_pedido_fecha ON intento_pago_simulado(id_pedido, fecha_intento DESC);
CREATE UNIQUE INDEX uq_intento_unico_confirmado
    ON intento_pago_simulado(id_pedido) WHERE resultado_confirmacion='CONFIRMADO';
COMMIT;
