-- AF-07 | Agente de apoyo (1 tabla). No ejecuta acciones automaticamente.
BEGIN;
CREATE TABLE recomendacion (
    id_recomendacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(24) NOT NULL CHECK (tipo IN ('REABASTECIMIENTO','PROMOCION_ACADEMICA')),
    id_producto BIGINT REFERENCES producto(id_producto) ON DELETE RESTRICT,
    id_curso BIGINT REFERENCES curso(id_curso) ON DELETE RESTRICT,
    motivo TEXT NOT NULL CHECK (btrim(motivo) <> ''),
    fecha_generacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    estado VARCHAR(10) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE','REVISADA')),
    fecha_revision TIMESTAMPTZ NULL,
    id_revisor BIGINT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
    CONSTRAINT ck_recomendacion_destino CHECK (
      (tipo='REABASTECIMIENTO' AND id_producto IS NOT NULL AND id_curso IS NULL)
      OR (tipo='PROMOCION_ACADEMICA' AND id_curso IS NOT NULL AND id_producto IS NULL)
    ),
    CONSTRAINT ck_recomendacion_revision CHECK (
      (estado='PENDIENTE' AND fecha_revision IS NULL AND id_revisor IS NULL)
      OR (estado='REVISADA' AND fecha_revision IS NOT NULL AND id_revisor IS NOT NULL)
    )
);
CREATE INDEX idx_recomendacion_estado_fecha ON recomendacion(estado, fecha_generacion DESC);
-- Evita mas de una recomendacion pendiente de reabastecimiento por producto.
CREATE UNIQUE INDEX uq_reabastecimiento_pendiente_producto
    ON recomendacion(id_producto)
    WHERE tipo='REABASTECIMIENTO' AND estado='PENDIENTE';
-- No imponer regla de duplicados de cursos hasta cerrar el comportamiento del agente.
COMMIT;
