-- AF-02 | Catalogo e inventario (3 tablas)
BEGIN;
CREATE TABLE categoria (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL CHECK (btrim(nombre) <> '')
);
CREATE UNIQUE INDEX uq_categoria_nombre_ci ON categoria(lower(btrim(nombre)));

CREATE TABLE producto (
    id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria BIGINT NOT NULL REFERENCES categoria(id_categoria) ON DELETE RESTRICT,
    codigo VARCHAR(60) NOT NULL CHECK (btrim(codigo) <> ''),
    nombre VARCHAR(180) NOT NULL CHECK (btrim(nombre) <> ''),
    descripcion TEXT, -- Opcional: el CSV ETL no exige descripcion.
    precio NUMERIC(12,2) NOT NULL CHECK (precio > 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    existencias INTEGER NOT NULL DEFAULT 0 CHECK (existencias >= 0),
    imagen_url VARCHAR(500) NULL CHECK (imagen_url IS NULL OR btrim(imagen_url) <> '')
);
CREATE UNIQUE INDEX uq_producto_codigo_ci ON producto(lower(btrim(codigo)));
CREATE INDEX idx_producto_categoria_activo ON producto(id_categoria, activo);
CREATE INDEX idx_producto_nombre ON producto(nombre);

-- Id_pedido y id_ejecucion se enlazan en el archivo 09 una vez creadas esas tablas.
-- Tipo determina si aumenta o disminuye el inventario: cantidad siempre positiva.
CREATE TABLE movimiento_inventario (
    id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto BIGINT NOT NULL REFERENCES producto(id_producto) ON DELETE RESTRICT,
    tipo VARCHAR(24) NOT NULL CHECK (tipo IN (
        'ENTRADA_MANUAL','AJUSTE_POSITIVO','AJUSTE_NEGATIVO','VENTA','ENTRADA_ETL')),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    motivo TEXT,
    fecha TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    id_responsable BIGINT REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
    id_pedido BIGINT NULL,
    id_ejecucion BIGINT NULL,
    CONSTRAINT ck_mov_origen CHECK (
      (tipo IN ('ENTRADA_MANUAL','AJUSTE_POSITIVO','AJUSTE_NEGATIVO')
          AND id_responsable IS NOT NULL AND id_pedido IS NULL AND id_ejecucion IS NULL)
      OR (tipo='VENTA' AND id_responsable IS NULL AND id_pedido IS NOT NULL AND id_ejecucion IS NULL)
      OR (tipo='ENTRADA_ETL' AND id_responsable IS NULL AND id_pedido IS NULL AND id_ejecucion IS NOT NULL)
    ),
    CONSTRAINT ck_mov_ajuste_motivo CHECK (
      tipo NOT IN ('AJUSTE_POSITIVO','AJUSTE_NEGATIVO') OR
      (motivo IS NOT NULL AND btrim(motivo) <> '')
    )
);
CREATE INDEX idx_movimiento_producto_fecha ON movimiento_inventario(id_producto, fecha DESC);
CREATE INDEX idx_movimiento_responsable ON movimiento_inventario(id_responsable);
CREATE INDEX idx_movimiento_pedido ON movimiento_inventario(id_pedido);
CREATE INDEX idx_movimiento_ejecucion ON movimiento_inventario(id_ejecucion);
COMMIT;
