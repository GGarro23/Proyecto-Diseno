-- AF-01 | Usuarios y acceso (5 tablas). Sin cuentas de usuario de prueba.
BEGIN;

CREATE TABLE usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL CHECK (btrim(nombre) <> ''),
    correo VARCHAR(254) NOT NULL CHECK (btrim(correo) <> '' AND position('@' IN correo) > 1),
    contrasena_hash TEXT NOT NULL CHECK (length(btrim(contrasena_hash)) >= 20),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX uq_usuario_correo_ci ON usuario (lower(btrim(correo)));

CREATE TABLE rol (
    id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL CHECK (btrim(nombre) <> ''),
    descripcion TEXT
);
CREATE UNIQUE INDEX uq_rol_nombre_ci ON rol (lower(btrim(nombre)));

CREATE TABLE permiso (
    id_permiso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(100) NOT NULL CHECK (btrim(codigo) <> ''),
    descripcion TEXT
);
CREATE UNIQUE INDEX uq_permiso_codigo_ci ON permiso (lower(btrim(codigo)));

CREATE TABLE usuario_rol (
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
    id_rol BIGINT NOT NULL REFERENCES rol(id_rol) ON DELETE RESTRICT,
    PRIMARY KEY (id_usuario, id_rol)
);
CREATE INDEX idx_usuario_rol_rol ON usuario_rol(id_rol);

CREATE TABLE rol_permiso (
    id_rol BIGINT NOT NULL REFERENCES rol(id_rol) ON DELETE RESTRICT,
    id_permiso BIGINT NOT NULL REFERENCES permiso(id_permiso) ON DELETE RESTRICT,
    PRIMARY KEY (id_rol, id_permiso)
);
CREATE INDEX idx_rol_permiso_permiso ON rol_permiso(id_permiso);

