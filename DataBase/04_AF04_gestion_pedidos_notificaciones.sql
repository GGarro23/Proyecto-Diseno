-- AF-04 | Gestion operativa y notificaciones (2 tablas).
BEGIN;
CREATE TABLE historial_estado_pedido (
    id_cambio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL REFERENCES pedido(id_pedido) ON DELETE RESTRICT,
    estado_anterior VARCHAR(20) NOT NULL CHECK (estado_anterior IN (
        'PENDIENTE','EN_PREPARACION','EMPACADO','ENVIADO','LISTO_RETIRO','RETIRADO')),
    estado_nuevo VARCHAR(20) NOT NULL CHECK (estado_nuevo IN (
        'PENDIENTE','EN_PREPARACION','EMPACADO','ENVIADO','LISTO_RETIRO','RETIRADO')),
    fecha_cambio TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    id_responsable BIGINT NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
    CONSTRAINT ck_historial_estado_diferente CHECK (estado_anterior <> estado_nuevo)
);
CREATE INDEX idx_historial_pedido_fecha ON historial_estado_pedido(id_pedido, fecha_cambio DESC);
CREATE INDEX idx_historial_responsable ON historial_estado_pedido(id_responsable);

-- id_inscripcion se enlaza en 09 tras crear AF-05.
CREATE TABLE notificacion_correo (
    id_notificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
    tipo_evento VARCHAR(32) NOT NULL CHECK (tipo_evento IN (
        'COMPRA_CONFIRMADA','CAMBIO_ESTADO_PEDIDO','INSCRIPCION_CONFIRMADA')),
    destinatario VARCHAR(254) NOT NULL CHECK (position('@' IN destinatario) > 1),
    estado_solicitud VARCHAR(12) NOT NULL CHECK (estado_solicitud IN ('ACEPTADA','RECHAZADA')),
    fecha_solicitud TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    detalle_error TEXT,
    id_pedido BIGINT REFERENCES pedido(id_pedido) ON DELETE RESTRICT,
    id_inscripcion BIGINT NULL,
    CONSTRAINT ck_notificacion_origen CHECK (
        (tipo_evento IN ('COMPRA_CONFIRMADA','CAMBIO_ESTADO_PEDIDO')
             AND id_pedido IS NOT NULL AND id_inscripcion IS NULL)
        OR (tipo_evento='INSCRIPCION_CONFIRMADA'
             AND id_pedido IS NULL AND id_inscripcion IS NOT NULL)
    )
);
CREATE INDEX idx_notificacion_usuario_fecha ON notificacion_correo(id_usuario, fecha_solicitud DESC);
CREATE INDEX idx_notificacion_pedido ON notificacion_correo(id_pedido);
CREATE INDEX idx_notificacion_inscripcion ON notificacion_correo(id_inscripcion);
COMMIT;
