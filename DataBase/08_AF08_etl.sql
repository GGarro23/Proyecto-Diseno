-- AF-08 | Importacion CSV y seguimiento (2 tablas).
BEGIN;
CREATE TABLE ejecucion_etl (
    id_ejecucion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_administrador BIGINT NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
    nombre_archivo VARCHAR(255) NOT NULL CHECK (btrim(nombre_archivo) <> ''),
    fecha_ejecucion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    estado VARCHAR(24) NOT NULL CHECK (estado IN ('EXITOSA','PARCIALMENTE_EXITOSA','FALLIDA')),
    filas_aceptadas INTEGER NOT NULL DEFAULT 0 CHECK (filas_aceptadas >= 0),
    filas_rechazadas INTEGER NOT NULL DEFAULT 0 CHECK (filas_rechazadas >= 0),
    CONSTRAINT ck_etl_estado_conteos CHECK (
       (estado='EXITOSA' AND filas_rechazadas=0)
       OR (estado='PARCIALMENTE_EXITOSA' AND filas_aceptadas>0 AND filas_rechazadas>0)
       OR (estado='FALLIDA' AND filas_aceptadas=0)
    )
);
CREATE INDEX idx_ejecucion_etl_fecha ON ejecucion_etl(fecha_ejecucion DESC);
CREATE INDEX idx_ejecucion_etl_administrador ON ejecucion_etl(id_administrador);

CREATE TABLE error_etl (
    id_error BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ejecucion BIGINT NOT NULL REFERENCES ejecucion_etl(id_ejecucion) ON DELETE RESTRICT,
    numero_fila INTEGER NULL CHECK (numero_fila IS NULL OR numero_fila > 0),
    campo VARCHAR(80) NULL,
    motivo TEXT NOT NULL CHECK (btrim(motivo) <> '')
);
CREATE INDEX idx_error_etl_ejecucion_fila ON error_etl(id_ejecucion, numero_fila);
COMMIT;
